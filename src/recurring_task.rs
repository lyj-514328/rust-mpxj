//! Corresponds to Java: `org/mpxj/RecurringTask.java`
//!
//! Represents a "recurring task record" in an MPX file.
//!
//! # Differences from Java: restoring `extends` with `Deref`
//!
//! Java's `RecurringTask extends RecurringData` and does **not override** any method of the base class,
//! it only adds `getDuration()` / `setDuration()` and overrides `toString()`.
//! Rust has no inheritance; this type restores it with **composition + `Deref`/`DerefMut`**: it holds a
//! [`RecurringData`], and via `Deref` all base class methods can be called directly on `RecurringTask`
//! (`task.get_start_date()` is `task.data.get_start_date()`),
//! thus avoiding about 30 pure-forwarding boilerplate methods.
//!
//! This crate uses `Deref`/`DerefMut` to restore inheritance only when the subclass **does not override** any base class method
//! (this file and `crate::mpp::props8` / `props9` / `props12` / `props14`). Whenever a subclass needs to
//! override base class behavior, this crate always uses explicit "composition + forwarding" so that methods can be compared with Java one by one.

use std::fmt;

use crate::duration::Duration;
use crate::recurring_data::RecurringData;

/// Corresponds to Java: `public final class RecurringTask extends RecurringData`
pub struct RecurringTask {
/// Corresponds to Java: all fields of the base class `RecurringData`
    data: RecurringData,

    /// Corresponds to Java: `private Duration m_duration;`
    duration: Option<Duration>,
}

impl RecurringTask {
/// Corresponds to Java: default constructor (implicitly generated by the Java compiler)
    pub fn new() -> Self {
        Self {
            data: RecurringData::new(),
            duration: None,
        }
    }

/// Get the recurring task's duration.
    ///
    /// Corresponds to Java: `public Duration getDuration()`
    pub fn get_duration(&self) -> Option<Duration> {
        self.duration
    }

/// Set the recurring task's duration.
    ///
    /// Corresponds to Java: `public void setDuration(Duration duration)`
    pub fn set_duration(&mut self, duration: Option<Duration>) {
        self.duration = duration;
    }

/// Get a read-only reference to the base class data (Rust-specific, for cases that need explicit access to `RecurringData`).
    pub fn get_recurring_data(&self) -> &RecurringData {
        &self.data
    }

/// Get a mutable reference to the base class data (Rust-specific).
    pub fn get_recurring_data_mut(&mut self) -> &mut RecurringData {
        &mut self.data
    }
}

impl Default for RecurringTask {
    fn default() -> Self {
        Self::new()
    }
}

impl std::ops::Deref for RecurringTask {
    type Target = RecurringData;

/// Corresponds to Java: "base class methods can be called directly" provided by the inheritance relationship
    fn deref(&self) -> &Self::Target {
        &self.data
    }
}

impl std::ops::DerefMut for RecurringTask {
/// Corresponds to Java: "base class methods can be called directly" provided by the inheritance relationship
    fn deref_mut(&mut self) -> &mut Self::Target {
        &mut self.data
    }
}

impl fmt::Display for RecurringTask {
    /// Corresponds to Java: `@Override public String toString()`
    ///
/// Java appends `super.toString()` only when `m_duration != null`,
/// and uses `println` for the last line (with a newline). Both are preserved item by item here.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "[RecurringTask")?;

        if self.duration.is_some() {
            write!(f, "{}", self.data)?;
        }

        writeln!(f, "]")
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::recurrence_type::RecurrenceType;
    use chrono::NaiveDate;

    fn date(year: i32, month: u32, day: u32) -> NaiveDate {
        NaiveDate::from_ymd_opt(year, month, day).unwrap()
    }

    #[test]
    fn duration_accessors_round_trip() {
        let mut task = RecurringTask::new();
        assert_eq!(task.get_duration(), None);

        task.set_duration(Some(Duration::get_instance_int(3, crate::time_unit::TimeUnit::Days)));

        assert!(task.get_duration().is_some());
// Default is equivalent to the implicit no-argument constructor
        assert_eq!(RecurringTask::default().get_duration(), None);
    }

    #[test]
    fn parent_methods_are_reachable_through_deref() {
// Corresponds to Java: inheritance makes base class methods directly callable
        let mut task = RecurringTask::new();

        task.set_recurrence_type(Some(RecurrenceType::Daily));
        task.set_start_date(Some(date(2026, 9, 20)));
        task.set_occurrences(Some(2));

        assert_eq!(task.get_recurrence_type(), Some(RecurrenceType::Daily));
        assert_eq!(task.get_start_date(), Some(date(2026, 9, 20)));
        assert_eq!(task.get_occurrences(), Some(2));
    }

    #[test]
    fn display_omits_parent_when_duration_is_absent() {
// Corresponds to Java: do not print super.toString() when `m_duration == null`
        let task = RecurringTask::new();
        assert_eq!(task.to_string(), "[RecurringTask]\n");
    }

    #[test]
    fn display_includes_parent_when_duration_is_present() {
        let mut task = RecurringTask::new();
        task.set_duration(Some(Duration::get_instance_int(1, crate::time_unit::TimeUnit::Days)));

        let text = task.to_string();
        assert!(text.starts_with("[RecurringTask"));
        assert!(text.ends_with("]\n"));
// When there is a duration, the base class's Display content is included as well
        assert!(text.len() > "[RecurringTask]\n".len());
    }
}
